#!/usr/bin/env node
/**
 * Generate the Code Mode index of host-function output types (ADR-0124 decision 3).
 *
 * TypeScript 7 has no JavaScript compiler API, so this script asks the compiler through declaration
 * emit: it compiles `packages/assistant/codegen/code-mode-guest-index.ts`, whose `guest<T>()` calls
 * print as the expanded JSON form of each tool's result type, and copies each printed type into
 * `guest-index.generated.ts`.
 *
 *   node scripts/generate-code-mode-index.mjs          write the file
 *   node scripts/generate-code-mode-index.mjs --check  fail when the file is stale (`pnpm check`)
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

const PACKAGE = join(ROOT, "packages/assistant");

const OUTPUT = join(PACKAGE, "src/tool-runtime/code-mode/guest-index.generated.ts");

const TSC = join(ROOT, "node_modules/.bin/tsc");

const OXFMT = join(ROOT, "node_modules/.bin/oxfmt");

const check = process.argv.includes("--check");

function emitDeclarations() {
  const outDir = mkdtempSync(join(tmpdir(), "code-mode-index-"));

  try {
    execFileSync(TSC, ["-p", "tsconfig.codegen.json", "--outDir", outDir], {
      cwd: PACKAGE,
      stdio: ["ignore", "inherit", "inherit"],
    });

    return readFileSync(join(outDir, "codegen/code-mode-guest-index.d.ts"), "utf8");
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
}

/** The printed entries of `GUEST_OUTPUTS`, in source order. */
function entries(declarations) {
  const start = declarations.indexOf("export declare const GUEST_OUTPUTS: {\n");

  if (start < 0) throw new Error("GUEST_OUTPUTS is missing from the emitted declarations");

  const body = declarations.slice(start).split("\n").slice(1);
  /** @type {{ path: string, lines: string[] }[]} */
  const out = [];
  /** @type {{ path: string, lines: string[] } | null} */
  let current = null;

  for (const line of body) {
    if (line === "};") break;
    // The printer indents a top-level key by exactly four spaces.
    const key = /^ {4}"([^"]+)": (.*)$/.exec(line);

    if (key) {
      current = { path: key[1], lines: [key[2]] };
      out.push(current);
    } else if (current) {
      current.lines.push(line);
    } else {
      throw new Error(`unexpected line before the first entry: ${line}`);
    }
  }

  return out.map(({ path, lines }) => ({ path, type: compact(path, lines.join("\n")) }));
}

/** Remove the markers that `Guest<T>` adds, and print the type on one line. */
function compact(path, printed) {
  const type = printed
    .replace(/^\s*"\\u00A7"\?: never;\n/gm, "")
    .replaceAll('"§JsonValue"', "JsonValue")
    .replaceAll('"§', '"')
    .replace(/\s+/g, " ")
    .replaceAll("; }", " }")
    .replaceAll("{ }", "{}")
    .trim()
    .replace(/;$/, "");

  for (const leftover of ["§", "\\u00A7", "import(", "/*elided*/", "any"]) {
    // `any` as a word only: a key such as `company` must pass.
    const found = leftover === "any" ? /\bany\b/.test(type) : type.includes(leftover);

    if (found) {
      throw new Error(`${path}: the printed type still holds '${leftover}': ${type.slice(0, 200)}`);
    }
  }

  return type;
}

function render(items) {
  const lines = items.map(
    ({ path, type }) => `  ${JSON.stringify(path)}: ${JSON.stringify(type)},`,
  );

  return [
    "// Generated by `node scripts/generate-code-mode-index.mjs` from",
    "// packages/assistant/codegen/code-mode-guest-index.ts. Do not edit.",
    "",
    "/**",
    " * The JSON type that each Code Mode host function returns (ADR-0124 decision 3). `JsonValue`",
    " * is any JSON value.",
    " */",
    "export const GUEST_OUTPUT_TYPES = {",
    ...lines,
    "} as const;",
    "",
  ].join("\n");
}

function formatted(source) {
  const dir = mkdtempSync(join(tmpdir(), "code-mode-index-fmt-"));
  const file = join(dir, "guest-index.generated.ts");

  try {
    writeFileSync(file, source);
    execFileSync(OXFMT, ["--write", file], { cwd: ROOT, stdio: ["ignore", "ignore", "inherit"] });

    return readFileSync(file, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const next = formatted(render(entries(emitDeclarations())));

if (check) {
  let current = "";

  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    // A missing file is stale.
  }

  if (current !== next) {
    console.error(
      "[code-mode-index] guest-index.generated.ts is stale. Run: node scripts/generate-code-mode-index.mjs",
    );
    process.exit(1);
  }

  console.log("[code-mode-index] up to date");
} else {
  writeFileSync(OUTPUT, next);
  console.log(`[code-mode-index] wrote ${OUTPUT.slice(ROOT.length)}`);
}
