// Writes the LGD district table that the NDMA Sachet warnings match uses
// (ADR-0117 decision 4). Sachet names a district by its LGD (Local Government
// Directory) code, and the geocode names it by its English name, so the
// briefing needs the table between the two.
//
// The source is the `lgd-latest` release of ramSeraph/opendata (UNLICENSE),
// which mirrors lgdirectory.gov.in every day. India adds districts a few times
// a year; run this again when Sachet names a code that the table does not have.
//
// Usage (this script does no network call; `gh` downloads the input):
//   gh release download lgd-latest -R ramSeraph/opendata -p "districts.<date>.csv.7z" -D <dir>
//   bsdtar -xf <dir>/districts.<date>.csv.7z -C <dir>
//   node scripts/generate-lgd-districts.mjs <dir>/districts.<date>.csv.7z <dir>/districts.<date>.csv
//
// The `lgd-latest` tag moves, so the generated header records the input: the
// name, the byte size, and the SHA-256 of the release asset and of the CSV in it.
// To verify the table:
//   1. Download the asset that the header names, with the command above.
//   2. Compare its SHA-256 (`shasum -a 256 <file>`) with the header. The `digest`
//      field of `gh release view lgd-latest -R ramSeraph/opendata --json assets`
//      also gives it.
//   3. Extract the CSV, and run this script with the two files.
//   4. Run `git diff --exit-code packages/assistant/src/briefings/warnings/lgd-districts.ts`.
//      No diff means that the table and its header come from that input.
// The release keeps only the newest dated asset. When a newer date replaces the
// asset, the old input is not on the release, and the header SHA-256 is the only
// record of it.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";

const OUT = resolve(
  import.meta.dirname,
  "../packages/assistant/src/briefings/warnings/lgd-districts.ts",
);

const STATE_NAME = "State Name (In English)";

const DISTRICT_CODE = "District Code";

const DISTRICT_NAME = "District Name(In English)";

const [assetPath, csvPath] = process.argv.slice(2);

if (!assetPath || !csvPath) {
  console.error(
    "usage: node scripts/generate-lgd-districts.mjs <districts.<date>.csv.7z> <districts.<date>.csv>",
  );
  process.exit(1);
}

// The CSV must be the one file in the asset, so the header names one input.
if (basename(assetPath) !== `${basename(csvPath)}.7z`) {
  console.error(`${basename(csvPath)} is not the CSV of the asset ${basename(assetPath)}`);
  process.exit(1);
}

/** A file, with the name, the byte size, and the SHA-256 that the header records. */
const readInput = (path) => {
  const bytes = readFileSync(path);

  return {
    bytes,
    name: basename(path),
    size: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  };
};

const asset = readInput(assetPath);

const csv = readInput(csvPath);

// The release CSV has no quoted fields. Fail loudly if that changes, so a comma
// inside a name never shifts a column without notice. The text is the bytes that
// the header hash covers.
const text = csv.bytes.toString("utf8");

if (text.includes('"')) {
  console.error("the CSV has quoted fields; this script reads only unquoted CSV");
  process.exit(1);
}

const [header, ...lines] = text.split(/\r?\n/).filter((line) => line.trim().length > 0);

const columns = header.split(",").map((column) => column.trim());

const index = (name) => {
  const at = columns.indexOf(name);

  if (at === -1) {
    console.error(`missing column "${name}" in ${columns.join(", ")}`);
    process.exit(1);
  }

  return at;
};

const stateAt = index(STATE_NAME);

const codeAt = index(DISTRICT_CODE);

const nameAt = index(DISTRICT_NAME);

const rows = lines.map((line, n) => {
  const fields = line.split(",").map((field) => field.trim());
  const code = Number.parseInt(fields[codeAt] ?? "", 10);

  if (!Number.isInteger(code) || !fields[stateAt] || !fields[nameAt]) {
    console.error(`bad row ${n + 2}: ${line}`);
    process.exit(1);
  }

  return { state: fields[stateAt], code, name: fields[nameAt] };
});

rows.sort((a, b) => a.code - b.code);

// The formatter's own spacing, so a fresh run gives no format diff. The CSV has no quoted field,
// so no name holds a comma.
const body = rows
  .map(({ state, code, name }) => `  [${JSON.stringify(state)}, ${code}, ${JSON.stringify(name)}],`)
  .join("\n");

writeFileSync(
  OUT,
  `// Generated by scripts/generate-lgd-districts.mjs from ${csv.name}. Do not edit.
// Source: the lgd-latest release of github.com/ramSeraph/opendata (UNLICENSE), a daily mirror of
// lgdirectory.gov.in. ${rows.length} districts.
// Release asset: ${asset.name}, ${asset.size} bytes, SHA-256:
//   ${asset.sha256}
// Input CSV: ${csv.name}, ${csv.size} bytes, SHA-256:
//   ${csv.sha256}
// To verify the table, follow the usage comment in the script.

/** One district: its state, its LGD code, and its English name, as LGD spells them. */
export type LgdDistrict = readonly [state: string, code: number, district: string];

export const LGD_DISTRICTS: readonly LgdDistrict[] = [
${body}
];
`,
);

console.log(`wrote ${rows.length} districts to ${OUT}`);
