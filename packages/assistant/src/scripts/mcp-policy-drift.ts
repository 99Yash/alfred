/**
 * Lists the drift between the code-owned read pins (`connections/mcp/built-in-tool-pins.ts`)
 * and the live Google Workspace MCP catalogs (ADR-0096 amendment, 2026-11-13). A read whose
 * descriptor drifted waits for approval again until its pin changes.
 *
 * Run: pnpm --filter @alfred/assistant mcp:policy-drift [--user <userId>] [--write]
 * `--write` rewrites the pins from the live tools that assert `readOnlyHint`. Review the diff
 * before you commit: each pin approves one exact descriptor as a read.
 * Exit 1 when a pin drifted, a pin has no live read, or a live read has no pin.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import {
  builtInReadToolPinsOf,
  descriptorHash,
  readLiveGoogleWorkspaceCatalogs,
  type BuiltInProvider,
} from "@alfred/assistant/connections/mcp";
import { db } from "@alfred/db";
import { integrationCredentials } from "@alfred/db/schemas";
import { eq } from "drizzle-orm";

const PINS_FILE = fileURLToPath(
  new URL("../connections/mcp/built-in-tool-pins.ts", import.meta.url),
);

const { values } = parseArgs({
  options: { user: { type: "string" }, write: { type: "boolean", default: false } },
});

async function resolveUserId(): Promise<string> {
  if (values.user) return values.user;

  const rows = await db()
    .selectDistinct({ userId: integrationCredentials.userId })
    .from(integrationCredentials)
    .where(eq(integrationCredentials.provider, "google"));

  const [only] = rows;

  if (!only || rows.length > 1) {
    throw new Error(`Pass --user: ${rows.length} users have a Google credential`);
  }

  return only.userId;
}

function renderPins(live: ReadonlyMap<BuiltInProvider, Record<string, string>>): string {
  const blocks = [...live].map(([provider, pins]) => {
    const lines = Object.entries(pins)
      .toSorted(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
      .map(([name, hash]) => `    ${name}: ${JSON.stringify(hash)},`);

    return `  ${provider}: {\n${lines.join("\n")}\n  },`;
  });

  return `/**
 * Descriptor-hash pins of the built-in read tools (\`built-in-tool-policy.ts\`). Generated by
 * \`pnpm --filter @alfred/assistant mcp:policy-drift --write\`. Review the diff before you commit:
 * each pin approves one exact descriptor as a read.
 */

import type { BuiltInMCPProvider } from "@alfred/contracts";

/** Remote tool name to descriptor hash, for each built-in that has read pins. */
export type BuiltInReadToolPins = Partial<
  Record<BuiltInMCPProvider, Readonly<Record<string, string>>>
>;

export const BUILT_IN_READ_TOOL_PINS = {
${blocks.join("\n")}
} as const satisfies BuiltInReadToolPins;
`;
}

const userId = await resolveUserId();

const catalogs = await readLiveGoogleWorkspaceCatalogs(userId);

const live = new Map<BuiltInProvider, Record<string, string>>();

const findings: string[] = [];

for (const { provider, tools } of catalogs) {
  const reads: Record<string, string> = {};

  for (const tool of tools) {
    if (tool.annotations?.readOnlyHint === true) reads[tool.name] = descriptorHash(tool);
  }

  live.set(provider, reads);
  const pins = builtInReadToolPinsOf(provider) ?? {};

  for (const [name, hash] of Object.entries(reads)) {
    if (!Object.hasOwn(pins, name)) findings.push(`unpinned  ${provider}.${name}`);
    else if (pins[name] !== hash) findings.push(`drifted   ${provider}.${name}`);
  }

  for (const name of Object.keys(pins)) {
    if (!Object.hasOwn(reads, name)) findings.push(`gone      ${provider}.${name}`);
  }
}

console.log(
  `Live read tools: ${[...live.values()].reduce((n, r) => n + Object.keys(r).length, 0)}`,
);

console.log(findings.length === 0 ? "No drift." : findings.join("\n"));

if (values.write) {
  writeFileSync(PINS_FILE, renderPins(live));
  execFileSync("pnpm", ["exec", "oxfmt", PINS_FILE], { stdio: "inherit" });
  console.log(`Wrote ${PINS_FILE}. Review the diff before you commit.`);
}

process.exit(findings.length === 0 || values.write ? 0 : 1);
